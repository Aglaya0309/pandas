import pandas as pd
import numpy as np

data = {
    'Ученик': ['Алиса', 'Борис', 'Евгений', 'Павел', 'Ева', 'Александр', 'Ольга', 'Анна', 'Лариса', 'Ашот'],
    'Математика': [5, 4, 3, 5, 4, 3, 5, 4, 3, 5],
    'Биология': [4, 3, 5, 4, 3, 5, 4, 3, 5, 4],
    'Химия': [3, 5, 4, 3, 5, 4, 3, 5, 4, 3],
    'История': [5, 4, 3, 5, 4, 3, 5, 4, 3, 5],
    'Физика': [4, 3, 5, 4, 3, 5, 4, 3, 5, 4]
}

df = pd.DataFrame(data)

print(df.head())

mean_scores = df.mean(numeric_only=True)
print("Средние оценки по предметам:")
print(mean_scores.to_string())

median_scores = df.median(numeric_only=True)
print("Медианные оценки по предметам:")
print(median_scores.to_string())

Q1_math = df['Математика'].quantile(0.25)
Q3_math = df['Математика'].quantile(0.75)
IQR_math = Q3_math - Q1_math

print("Статистика по математике:")
print(f"Q1 (25-й процентиль): {Q1_math}")
print(f"Q3 (75-й процентиль): {Q3_math}")
print(f"IQR (интерквартильный размах): {IQR_math}")

std_scores = df.std(numeric_only=True)
print("Стандартное отклонение по предметам:")
print(std_scores.to_string())
